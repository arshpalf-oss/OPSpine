def create_pptx(prompt: str, opts: Dict = None) -> Tuple[str, str, int]:
    """Create a real PPTX file. Returns (filepath, filename, size)."""
    from pptx import Presentation
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor
    
    opts = opts or {}
    slides_data = _generate_slide_content(prompt)
    
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    
    for sd in slides_data:
        if sd["layout"] == "title":
            slide = prs.slides.add_slide(prs.slide_layouts[0])
            slide.shapes.title.text = sd["title"]
            if len(slide.placeholders) > 1:
                slide.placeholders[1].text = sd["subtitle"]
        else:
            slide = prs.slides.add_slide(prs.slide_layouts[1])
            slide.shapes.title.text = sd["title"]
            tf = slide.placeholders[1].text_frame if len(slide.placeholders) > 1 else None
            if tf and "bullets" in sd:
                tf.text = sd["bullets"][0]
                for b in sd["bullets"][1:]:
                    p = tf.add_paragraph()
                    p.text = b
                    p.level = 0
    
    ts = int(time.time())
    fname = f"presentation_{ts}.pptx"
    fpath = DOCS_DIR / fname
    prs.save(str(fpath))
    size = fpath.stat().st_size
    return str(fpath), fname, size


def create_docx(prompt: str, opts: Dict = None) -> Tuple[str, str, int]:
    """Create a real DOCX file."""
    from docx import Document
    from docx.shared import Pt, Inches, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    
    opts = opts or {}
    doc_type = opts.get("type", "document")
    
    doc = Document()
    
    # Title
    title = doc.add_heading(prompt[:100], level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    # Metadata
    meta = doc.add_paragraph()
    meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = meta.add_run(f"Generated by OPSpine Forge · {time.strftime('%B %d, %Y')}")
    run.font.size = Pt(10)
    run.font.color.rgb = RGBColor(120, 120, 120)
    
    doc.add_paragraph()
    
    sections = [
        ("Executive Summary", "This document was generated by OPSpine Forge using deterministic content engines. It provides a structured starting point that you can refine and expand."),
        ("Background", "Context and background information relevant to the subject matter. Fill in this section with specific details relevant to your project."),
        ("Key Points", ""),
        ("Analysis", "Detailed analysis of the topic, including supporting evidence, considerations, and implications."),
        ("Recommendations", [
            "Review and customize the generated content for your specific context",
            "Add specific data points and citations using Scout",
            "Export to PDF when ready for distribution",
            "Share via the Library for easy access across workspaces"
        ]),
        ("Next Steps", "Define concrete next actions and assign owners in the Working Board. Schedule deadlines in Kronos."),
    ]
    
    for heading, content in sections:
        doc.add_heading(heading, level=1)
        if isinstance(content, list):
            for item in content:
                doc.add_paragraph(item, style="List Bullet")
        elif content:
            doc.add_paragraph(content)
    
    ts = int(time.time())
    fname = f"document_{ts}.docx"
    fpath = DOCS_DIR / fname
    doc.save(str(fpath))
    size = fpath.stat().st_size
    return str(fpath), fname, size


def create_xlsx(prompt: str, opts: Dict = None) -> Tuple[str, str, int]:
    """Create a real XLSX file."""
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill, Alignment
    
    opts = opts or {}
    wb = Workbook()
    ws = wb.active
    ws.title = "Data"
    
    # Header row
    headers = ["ID", "Item", "Category", "Status", "Priority", "Notes"]
    header_fill = PatternFill(start_color="1a1a2e", end_color="1a1a2e", fill_type="solid")
    header_font = Font(color="FFFFFF", bold=True, size=11)
    
    for col, h in enumerate(headers, 1):
        cell = ws.cell(row=1, column=col, value=h)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center")
    
    # Sample data
    data = [
        [1, "Project setup", "Infrastructure", "Complete", "High", "Initial configuration done"],
        [2, "Design tokens", "Design", "Complete", "High", "Glass material system defined"],
        [3, "Database schema", "Backend", "Complete", "Critical", "All tables created"],
        [4, "AI Core", "Backend", "In Progress", "Critical", "Local fallbacks working"],
        [5, "Dashboard UI", "Frontend", "In Progress", "High", "Animated cards implemented"],
        [6, "Workspace shells", "Frontend", "Todo", "High", "All 8 environments needed"],
        [7, "File exports", "Forge", "Todo", "Medium", "PPTX/DOCX/XLSX/PDF"],
        [8, "QA & testing", "Quality", "Todo", "High", "Geometry and transition tests"],
    ]
    
    for r, row_data in enumerate(data, 2):
        for c, val in enumerate(row_data, 1):
            ws.cell(row=r, column=c, value=val)
    
    # Auto-width
    for col in ws.columns:
        max_len = max(len(str(cell.value or "")) for cell in col)
        ws.column_dimensions[col[0].column_letter].width = min(max_len + 4, 40)
    
    # Summary sheet
    ws2 = wb.create_sheet("Summary")
    ws2["A1"] = "Project Summary"
    ws2["A1"].font = Font(bold=True, size=14)
    ws2["A3"] = "Total Items:"
    ws2["B3"] = len(data)
    ws2["A4"] = "Generated:"
    ws2["B4"] = time.strftime("%Y-%m-%d %H:%M")
    ws2["A5"] = "Generator:"
    ws2["B5"] = "OPSpine Forge (local engine)"
    
    ts = int(time.time())
    fname = f"spreadsheet_{ts}.xlsx"
    fpath = DOCS_DIR / fname
    wb.save(str(fpath))
    size = fpath.stat().st_size
    return str(fpath), fname, size


def create_pdf(prompt: str, opts: Dict = None) -> Tuple[str, str, int]:
    """Create a real PDF file."""
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.colors import HexColor
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    from reportlab.lib.units import inch
    
    opts = opts or {}
    ts = int(time.time())
    fname = f"document_{ts}.pdf"
    fpath = DOCS_DIR / fname
    
    doc = SimpleDocTemplate(str(fpath), pagesize=letter,
                           leftMargin=0.75*inch, rightMargin=0.75*inch,
                           topMargin=1*inch, bottomMargin=1*inch)
    
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle('CustomTitle', parent=styles['Title'],
                                  textColor=HexColor('#1a1a2e'), fontSize=24, spaceAfter=12)
    h1 = ParagraphStyle('H1', parent=styles['Heading1'], textColor=HexColor('#1a1a2e'), fontSize=16)
    body = ParagraphStyle('Body', parent=styles['Normal'], fontSize=11, leading=16, spaceAfter=8)
    meta_style = ParagraphStyle('Meta', parent=styles['Normal'], fontSize=9, textColor=HexColor('#888888'))
    
    story = []
    story.append(Paragraph(prompt[:120], title_style))
    story.append(Paragraph(f"Generated by OPSpine Forge · {time.strftime('%B %d, %Y')} · Local Engine", meta_style))
    story.append(Spacer(1, 0.3*inch))
    
    story.append(Paragraph("Executive Summary", h1))
    story.append(Paragraph(
        "This document was produced by OPSpine Forge's deterministic document engine. "
        "It demonstrates real PDF generation with proper structure, formatting, and typography. "
        "The file contains a valid %PDF header and is fully readable by standard PDF viewers.", body))
    
    story.append(Paragraph("Capabilities", h1))
    items = [
        "Real PPTX generation via python-pptx",
        "Real DOCX generation via python-docx",
        "Real XLSX generation via openpyxl",
        "Real PDF generation via ReportLab",
        "Markdown export",
        "ZIP packaging of multiple files",
        "PNG generation (with Pillow or built-in fallback)",
    ]
    for item in items:
        story.append(Paragraph(f"• {item}", body))
    
    story.append(Paragraph("Document Structure", h1))
    data = [["Section", "Status", "Notes"],
            ["Content", "Generated", "Deterministic template"],
            ["Formatting", "Applied", "Typography, spacing, colors"],
            ["Validation", "Passed", "File header verified"]]
    t = Table(data, colWidths=[2*inch, 1.2*inch, 2.5*inch])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), HexColor('#1a1a2e')),
        ('TEXTCOLOR', (0,0), (-1,0), HexColor('#ffffff')),
        ('GRID', (0,0), (-1,-1), 0.5, HexColor('#cccccc')),
        ('FONTSIZE', (0,0), (-1,-1), 10),
        ('PADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(t)
    
    doc.build(story)
    size = fpath.stat().st_size
    return str(fpath), fname, size


